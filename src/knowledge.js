function buildGreeting() {
  const now = nowMoscow();
  const text = GREETING_VARIANTS[Math.floor(Math.random() * GREETING_VARIANTS.length)];
  if (!now.suggestSunset) return text;
  const sunset =
    'Сейчас близится вечер — как раз время подумать о выходе на закат в море сегодня — интересно?';
  const parts = text.split('\n');
  parts.splice(1, 0, sunset);
  return parts.join('\n');
}

