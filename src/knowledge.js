const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', 'knowledge');

let cached = null;

function readIfExists(filePath) {
  try {
    return fs.readFileSync(filePath, 'utf8').trim();
  } catch {
    return '';
  }
}

function loadKnowledge() {
  if (cached) return cached;

  const llms = readIfExists(path.join(ROOT, 'llms-full.txt'));
  const faq = readIfExists(path.join(ROOT, 'faq-extra.md'));

  cached = {
    llms,
    faq,
    combined: [llms, faq].filter(Boolean).join('\n\n---\n\n'),
  };

  return cached;
}

/** Текущие дата/время по Москве (для подсказок боту). */
function nowMoscow(date = new Date()) {
  const fmt = new Intl.DateTimeFormat('ru-RU', {
    timeZone: 'Europe/Moscow',
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  });
  const parts = Object.fromEntries(
    new Intl.DateTimeFormat('en-GB', {
      timeZone: 'Europe/Moscow',
      hour: '2-digit',
      minute: '2-digit',
      hour12: false,
    })
      .formatToParts(date)
      .filter((p) => p.type !== 'literal')
      .map((p) => [p.type, p.value])
  );
  const hour = Number(parts.hour);
  const minute = Number(parts.minute);
  return {
    label: fmt.format(date),
    hour,
    minute,
    /** окно «расскажи про закат»: 15:00–17:00 МСК */
    suggestSunset: hour >= 15 && hour < 17,
  };
}

