'use strict';

/** Групповая рыбалка — /gruppovaja_ribalka */
const GROUP_FISHING_RE =
  /gruppovaj\w*_ribalk|группов[а-яё]*\s+рыбал|рыбал[а-яё]*\s+группов|2800|2\s*800.*(?:рыбал|чел)|билет.*рыбал|рыбал.*билет|моряк[\s-]?попай.*групп|групп.*моряк[\s-]?попай|расписан.*рыбал|07:30.*рыбал|10:30.*13:30/i;

/** Трофейная / аренда катамарана целиком */
const TROPHY_FISHING_RE =
  /трофейн[а-яё]*\s+рыбал|катран|скат[а-яё]*(?:\s|$|[^a-zа-яё])|черноморск[а-яё]*\s+акул|морск[а-яё]*\s+(?:кот|лисиц)|аренд[а-яё]*\s+катамар[а-яё]*.*рыбал|рыбал[а-яё]*\s+катамар[а-яё]*\s+целик|20000|20\s*000.*рыбал|моряк[\s-]?попай.*(?:целик|аренд|трофей)/i;

/** Общий вопрос про рыбалку — уточнить формат */
const FISHING_FORMAT_RE =
  /(?:рыбал|fish).{0,50}(?:сколько|стоит|есть|можно|хочу|запис)|(?:сколько|стоит|есть|можно|хочу).{0,50}(?:рыбал|fish)/i;

function isGroupFishingIntent(text) {
  return GROUP_FISHING_RE.test(String(text || ''));
}

function isTrophyFishingIntent(text) {
  return TROPHY_FISHING_RE.test(String(text || ''));
}

function isFishingFormatClarifyIntent(text) {
  const t = String(text || '');
  if (isGroupFishingIntent(t) || isTrophyFishingIntent(t)) return false;
  return FISHING_FORMAT_RE.test(t);
}

