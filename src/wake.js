'use strict';

const WAKE_RE =
  /вейк(?:борд)?|wake(?:board)?|водн\w*\s+лыж|водные\s+лыжи|wake\s*board|фал/i;

function isWakeIntent(text) {
  return WAKE_RE.test(String(text || ''));
}

