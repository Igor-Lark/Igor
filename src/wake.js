'use strict';

const WAKE_RE =
  /вейк(?:борд)?|wake(?:board)?|водн\w*\s+лыж|водные\s+лыжи|wake\s*board/i;

function isWakeIntent(text) {
  return WAKE_RE.test(String(text || ''));
}

function buildWakeReply() {
  return [
    'Вейкборд — катание на доске за катером: катер тянет канат, гость едет по волне.',
    'Водные лыжи — катание на лыжах за катером; капитан подбирает скорость, новичкам помогает встать с воды.',
    'У нас для этого — быстроходный катер «Инфинити»: 8 000 ₽/час за весь катер с катанием на вейкборде или водных лыжах.',
    'Капитан — он же инструктор, подскажет и обучит. До 6 гостей, Сириус.',
  ].join('\n');
}

module.exports = {
  isWakeIntent,
  buildWakeReply,
};
