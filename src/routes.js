'use strict';

/** Маршрут прогулки по морю — не путать с «как пройти» к причалу. */
const SEA_ROUTE_RE =
  /маршрут\s+(?:по\s+)?мор|морск(?:ой|ая|ое)\s+маршрут|куда\s+(?:поплыв|пойд[ёe]м|плыв|ходим|едем)|как(?:ой|ие)\s+маршрут.*(?:мор|прогул)|маршрут\s+прогул|прогулк.*(?:куда|маршрут)|(?:куда|как)\s+(?:плыв|пойд)[ёe]м|далеко\s+от\s+берег|(?:от|за)\s+берег(?:а|овой)?|морск(?:ие|ой)\s+мил|на\s+сколько\s+(?:далеко|далеко\s+от\s+берег)/i;

/** «Маршрут» к причалу / схема — не морская прогулка. */
const PIER_ROUTE_RE =
  /как\s+пройт|как\s+добрат|как\s+дойти|как\s+вас\s+найти|как\s+найти|где\s+(?:вас\s+)?найти|где\s+причал|где\s+встрет|адрес|схем|парковк|легенд|линия\s*1|парусная\s*1|ул\.?\s*парусн|к\s+вам|к\s+причал/i;

function isSeaRouteIntent(text) {
  const t = String(text || '');
  if (!SEA_ROUTE_RE.test(t)) return false;
  if (PIER_ROUTE_RE.test(t)) return false;
  return true;
}

function buildSeaRouteReply() {
  return [
    'Маршрут по морю — любой на ваш выбор: к дельфинам, на купание, вдоль побережья, на закат — капитан подстроится под пожелания.',
    'Важно: выход не дальше 3 морских миль (6 км) от береговой линии.',
  ].join('\n');
}

module.exports = {
  isSeaRouteIntent,
  buildSeaRouteReply,
};
