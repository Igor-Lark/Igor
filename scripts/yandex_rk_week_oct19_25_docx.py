def shade(cell, hex_color: str) -> None:
    tcPr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), hex_color)
    shd.set(qn("w:val"), "clear")
    tcPr.append(shd)


def set_run(run, size=11, bold=False, color=None):
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Calibri")
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)


def p(doc, text, size=11, bold=False, space_after=6, color=None):
    para = doc.add_paragraph()
    para.paragraph_format.space_before = Pt(0)
    para.paragraph_format.space_after = Pt(space_after)
    para.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    r = para.add_run(text)
    set_run(r, size=size, bold=bold, color=color)
    return para


def h(doc, text, level=1):
    para = doc.add_heading(text, level=level)
    for run in para.runs:
        run.font.color.rgb = RGBColor(0x1A, 0x3A, 0x5C)
    return para


def table(doc, headers, rows):
    t = doc.add_table(rows=1 + len(rows), cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = True
    for i, htxt in enumerate(headers):
        cell = t.rows[0].cells[i]
        cell.text = ""
        para = cell.paragraphs[0]
        para.paragraph_format.space_before = Pt(2)
        para.paragraph_format.space_after = Pt(2)
        r = para.add_run(htxt)
        set_run(r, size=9, bold=True, color=(255, 255, 255))
        shade(cell, "1A3A5C")
    for ri, row in enumerate(rows):
        fill = "F4F7FA" if ri % 2 == 0 else "FFFFFF"
        for ci, val in enumerate(row):
            cell = t.rows[ri + 1].cells[ci]
            cell.text = ""
            para = cell.paragraphs[0]
            para.paragraph_format.space_before = Pt(1)
            para.paragraph_format.space_after = Pt(1)
            r = para.add_run(str(val))
            set_run(r, size=9)
            shade(cell, fill)
    doc.add_paragraph()
    return t


def bullet(doc, text, bold_prefix=None):
    para = doc.add_paragraph(style="List Bullet")
    para.paragraph_format.space_after = Pt(3)
    para.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    if bold_prefix:
        r = para.add_run(bold_prefix)
        set_run(r, size=11, bold=True)
        r2 = para.add_run(text)
        set_run(r2, size=11)
    else:
        r = para.add_run(text)
        set_run(r, size=11)
    return para


