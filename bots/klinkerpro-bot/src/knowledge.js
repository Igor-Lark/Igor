const fs = require('fs');
const path = require('path');

const { managerPhoneLink, SITE_TERMO, SITE_MAIN } = require('./contacts');

const FAQ_PATH = path.join(__dirname, '..', 'knowledge', 'faq.md');
const SITE_HOME_PATH = path.join(__dirname, '..', 'knowledge', 'site-home.md');
