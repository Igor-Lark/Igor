OUT_LOCAL = Path(__file__).resolve().parent.parent / "локальная" / OUT.name

NAVY = RGBColor(0x0B, 0x3D, 0x5C)
GRAY = RGBColor(0x33, 0x33, 0x33)
RED = RGBColor(0x8B, 0x1A, 0x1A)


def h(doc, text, level=1):
    p = doc.add_heading(text, level=level)
    for run in p.runs:
        run.font.color.rgb = NAVY
    return p


def p(doc, text, *, bold=False, color=None):
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.font.size = Pt(11)
    run.font.color.rgb = color or GRAY
    run.bold = bold
    return para


def bullet(doc, text, *, color=None):
    para = doc.add_paragraph(style="List Bullet")
    run = para.add_run(text)
    run.font.size = Pt(11)
    run.font.color.rgb = color or GRAY
    return para


