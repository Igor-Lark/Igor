def nlen(text: str) -> int:
    return len(text)


def words(text: str) -> list[str]:
    return re.findall(r"\S+", text)


def check(kind: str, text: str) -> None:
    limit, word_limit = LIMITS[kind]
    if nlen(text) > limit:
        raise SystemExit(f"{kind} {nlen(text)}>{limit}: {text}")
    long = [w for w in words(text) if len(w) > word_limit]
    if long:
        raise SystemExit(f"{kind} long word {long}: {text}")


